// Regenerates tests/manifest.js by scanning projects/ for the .py corpus and
// tagging each file by what it needs to run.
//
//   node tests/make-manifest.js
//
// This is a developer tool, not part of the app. The generated manifest.js is
// committed so the harness itself needs no build step.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const PROJECTS = path.join(ROOT, "projects");

// A tag means "this file needs something the automated diff can't provide".
// Anything with no blocking tag is diffed byte-for-byte against its golden.
const RULES = [
    // needs the network / a school ID / an API key. printImage, printYoutube
    // and playSound belong here too: they fetch a remote URL and block until
    // it loads or errors.
    ["network", /\b(setSchool|getOpenAI\w*|getChatGPTAnswer|getWeather\w*|getTranslation|logToServer|speak|playFreeSoundOrg|playSound|printImage|printYoutube|showIFrame|showGoogleVideo|cloud_|cloudconst|cloudfree|clouddel|[gs]etCloudVariable|delCloudVariable|getTestAPI|sendsms)\s*[(=]/],
    // blocks on a DOM widget nobody is going to click
    ["widgets", /\b(printButton|createButton|waitForButtonClick\w*|waitForButton|isButtonClick\w*|printTextbox|createTextbox|getTextboxContents)\s*\(/],
    // needs a physical device or camera/mic permission
    ["hardware", /\b(from\s+microbit\s+import|Microbit\s*\(|showWebCam|printWebCam|getWebCamImage|predictFrom\w+|predictPoseFromWebCam|getSkeletonFromWebCam|load(Pose|Audio|Image)Model|listen\s*\(|setHueBridgeIP|setLight|hue(light|bright|colour))\b/],
    // draws instead of printing - nothing textual to diff
    ["canvas", /^\s*(from|import)\s+(pyangelo|babylon|turtle)\b/m],
    // speech synthesis - fires and forgets, no text output
    ["speech", /^\s*(from|import)\s+speech\b|\bsay\s*\(/m],
    // output varies run to run unless seeded
    ["nondeterministic", /^\s*(from|import)\s+(random|time)\b|\b(randint|choice|shuffle|uniform|random|time)\s*\(/m],
    // blocks for keyboard input - needs a stdin fixture
    ["interactive", /\binput\s*\(/],
    // imports a classroom module (csinsc/goodies/pyangelo/...). Everything
    // without this tag needs only builtins and the stdlib, which is the
    // gate for the first stage of the Pyodide port.
    ["classroom", /^\s*(?:from|import)\s+(?:csinsc|goodies|pyangelo|microbit|speech|babylon|turtle|sprite|vector|sendsms)\b/m],
    // uses the non-CPython goto/label extension
    ["goto", /^\s*(goto|label)\s+\.?\w+\s*$/m],
    // training-wheels dialect - only parses with ?wheels=1
    ["wheels", /^\s*repeat\s+\d/m],
    // fill-in-the-blank scaffold: expected to fail
    ["blanks", /_{4,}/]
];

// Files that are deliberately broken so students read the error message.
const EXPECT_ERROR_DIRS = ["debugging"];

// Blocking tags exclude a file from the automated text diff.
const BLOCKING = ["network", "hardware", "canvas", "speech", "widgets"];

function walk(dir, out) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) walk(full, out);
        else if (entry.name.endsWith(".py")) out.push(full);
    }
    return out;
}

const rows = [];
for (const file of walk(PROJECTS, []).sort()) {
    const src = fs.readFileSync(file, "utf8");
    // path as ?project= wants it: forward slashes, no .py
    const rel = path.relative(PROJECTS, file).replace(/\\/g, "/").replace(/\.py$/, "");
    const tags = RULES.filter(([, re]) => re.test(src)).map(([tag]) => tag);
    // `blanks` deliberately does NOT imply expect-error: most fill-in-the-blank
    // scaffolds still parse and run, because the placeholder underscores sit
    // inside strings or happen to be valid identifiers. Whether a file is meant
    // to fail is decided by its recorded golden, not by a source regex.
    if (EXPECT_ERROR_DIRS.includes(rel.split("/")[0])) tags.push("expect-error");

    rows.push({
        path: rel,
        lines: src.split("\n").length,
        tags: tags,
        auto: !tags.some(t => BLOCKING.includes(t))
    });
}

const auto = rows.filter(r => r.auto).length;
const banner =
`// GENERATED by tests/make-manifest.js - do not edit by hand.
// ${rows.length} files, ${auto} runnable in the automated diff.
`;

fs.writeFileSync(
    path.join(__dirname, "manifest.js"),
    banner + "var MANIFEST = " + JSON.stringify(rows, null, 1) + ";\n"
);

// Report
const counts = {};
for (const r of rows) for (const t of r.tags) counts[t] = (counts[t] || 0) + 1;
console.log(`${rows.length} files -> tests/manifest.js`);
console.log(`  ${auto} automatable, ${rows.length - auto} manual-only`);
for (const [t, n] of Object.entries(counts).sort((a, b) => b[1] - a[1])) {
    console.log(`  ${String(n).padStart(4)}  ${t}`);
}
